/**
 * Regenerates src/components/ui/icon-sprite-data.ts from the INSTALLED
 * lucide-react, so sprite glyphs stay byte-identical to the components they
 * replaced. Run after a lucide-react upgrade:
 *   node scripts/icons/build-sprite.mjs
 */
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";
import { readFileSync, writeFileSync } from "node:fs";

// Every lucide icon rendered by the two page renderers that emit the sprite:
// country-seo/CountryLanding (/uae/, /india/, /gurgaon/, the 48 country pages)
// and mumbai-seo/MumbaiSeoLanding (/mumbai/).
//
// Nothing else is on this list on purpose. `<use href="#id">` resolves only
// against a symbol in the same document, so a component may only use <Icon> if
// EVERY page that renders it also renders <IconSprite/>. blog/BlogCardGrid
// (also on the homepage) and shared/SchoolStrip (also on ~4,000 generated
// pages and the Gurgaon landings) are rendered from pages with no sprite, so
// they still inline their icons -- 13 instances, ~4KB, against the 325
// instances and ~187KB these two renderers account for.
const USED = [
  "ArrowRight",
  "ArrowUpRight",
  "BadgeCheck",
  "BookOpen",
  "BookOpenCheck",
  "BrainCircuit",
  "Building2",
  "CalendarClock",
  "CircleCheck",
  "ClipboardCheck",
  "Clock3",
  "Compass",
  "FlaskConical",
  "GitBranch",
  "GraduationCap",
  "House",
  "Laptop",
  "Layers",
  "Link2",
  "ListChecks",
  "MapPin",
  "MapPinned",
  "MessageCircleQuestion",
  "MessageSquare",
  "Network",
  "Quote",
  "Scale",
  "SearchCheck",
  "ShieldAlert",
  "ShieldCheck",
  "Shuffle",
  "Sigma",
  "SignalHigh",
  "Sparkles",
  "Star",
];

const EXPECTED_HOST =
  '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="';

const out = [];
for (const pascal of USED) {
  const Cmp = lucide[pascal];
  if (!Cmp) throw new Error(`lucide-react has no export ${pascal}`);
  const html = renderToStaticMarkup(createElement(Cmp, {}));
  if (!html.startsWith(EXPECTED_HOST)) {
    throw new Error(`${pascal}: unexpected lucide host attributes:\n${html.slice(0, 260)}`);
  }
  const cls = /class="([^"]*)"/.exec(html)[1];
  const glyph = html.replace(/^<svg\b[^>]*>/, "").replace(/<\/svg>$/, "");
  // lucide's last `lucide-*` class is its canonical icon name (`clock-3`).
  const classes = cls.split(" ").filter((c) => c.startsWith("lucide-"));
  const name = classes[classes.length - 1].slice("lucide-".length);
  // `cls` minus the leading "lucide " base class -- Icon.tsx re-adds it.
  const suffix = cls.replace(/^lucide /, "");
  // Two lucide exports can share one rendered class (CheckCircle2 is an alias of
  // CircleCheck). Both would emit the same sprite key and the object literal would
  // silently keep the last -- so refuse rather than ship a sprite whose key count
  // disagrees with its entry count.
  const clash = out.find((e) => e.name === name);
  if (clash) throw new Error(`${pascal} and ${clash.pascal} both render as "${name}" -- keep only one in USED`);
  out.push({ name, suffix, glyph, pascal });
}
out.sort((a, b) => a.name.localeCompare(b.name));

const body = out
  .map(
    (i) =>
      `  ${JSON.stringify(i.name)}: {\n    cls: ${JSON.stringify(i.suffix)},\n    from: ${JSON.stringify(i.pascal)},\n    glyph: ${JSON.stringify(i.glyph)},\n  },`,
  )
  .join("\n");

writeFileSync(
  new URL("../../src/components/ui/icon-sprite-data.ts", import.meta.url),
  `// GENERATED by scripts/icons/build-sprite.mjs from lucide-react ${lucideVersion()}.
// Do not edit by hand -- re-run the script instead.
export const ICON_SPRITE = {
${body}
} as const;

export type IconName = keyof typeof ICON_SPRITE;
`,
  { encoding: "utf8" },
);

function lucideVersion() {
  const pkg = new URL("../../node_modules/lucide-react/package.json", import.meta.url);
  return JSON.parse(readFileSync(pkg, "utf8")).version;
}
