export function schoolsFor(board: KeywordPage["board"]): string[] {
  return board === "IGCSE" ? IGCSE_SCHOOLS : board === "IB" ? IB_SCHOOLS : [...new Set([...IB_SCHOOLS, ...IGCSE_SCHOOLS])];
}

export const ROOT = process.cwd();
export const TMP = path.join(ROOT, "tmp", "india-keywords");

function main(): void {
  const slugs = KEYWORD_PAGES.map((e) => e.slug);
  const problems: string[] = [];
  if (slugs.length !== 100) problems.push(`expected 100 pages, got ${slugs.length}`);
  if (new Set(slugs).size !== slugs.length) problems.push(`duplicate slug: ${slugs.filter((s, i) => slugs.indexOf(s) !== i).join(", ")}`);
  for (const e of KEYWORD_PAGES) {
    if (e.title.length > 60) problems.push(`${e.slug}: title ${e.title.length} chars`);
    if (e.description.length < 120 || e.description.length > 160) problems.push(`${e.slug}: description ${e.description.length} chars`);
    if (e.secondary.length !== 12) problems.push(`${e.slug}: ${e.secondary.length} secondary keywords`);
    if (e.mustCover.length < 6) problems.push(`${e.slug}: ${e.mustCover.length} mustCover items`);
    if (!e.regions.length) problems.push(`${e.slug}: no regions`);
    if (e.facts.some((f) => !f)) problems.push(`${e.slug}: an undefined fact was passed`);
  }
  if (problems.length) throw new Error(problems.join("\n"));

  mkdirSync(path.join(TMP, "briefs"), { recursive: true });
  mkdirSync(path.join(TMP, "agent-out"), { recursive: true });
  for (const e of KEYWORD_PAGES) {
    // Siblings: every other page, so no writer can echo a page on another board either.
    const siblings = KEYWORD_PAGES.filter((s) => s.slug !== e.slug).map((s) => ({ slug: s.slug, keyword: s.keyword, intent: s.intent }));
    const brief = {
      ...e,
      path: `/india/${e.slug}/`,
      regions: e.regions.map((k) => ({ key: k, ...REGIONS[k] })),
      metros: METROS.map((k) => REGIONS[k].name),
      schools: schoolsFor(e.board),
      siblings,
    };
    writeFileSync(path.join(TMP, "briefs", `${e.slug}.json`), `${JSON.stringify(brief, null, 1)}\n`);
  }
  writeFileSync(path.join(TMP, "keys.txt"), `${slugs.join("\n")}\n`);
  console.log(`wrote ${slugs.length} briefs -> ${path.relative(ROOT, path.join(TMP, "briefs"))}`);
}

if (/india-keywords[\\/]plan\.ts$/.test(process.argv[1] ?? "")) main();
