type Spec = Pick<KeywordPage, "slug" | "board" | "keyword" | "base" | "h1" | "title" | "description" | "intent" | "facts" | "mustCover" | "regions"> & {
  /** Four hand-written secondary phrases; eight city-qualified ones are generated. */
  extras: string[];
  cmp: ComparisonKey;
  focus?: string;
  subjects?: string[];
  programmes?: Array<"PYP" | "MYP" | "DP">;
  level?: string;
  pageType?: KeywordPage["pageType"];
};

const p = (e: Spec): KeywordPage => ({
  pageType: e.pageType ?? "city",
  programmes: e.programmes ?? (e.board === "IGCSE" ? [] : ["PYP", "MYP", "DP"]),
  subjects: e.subjects ?? (e.board === "IB" ? IB_SUBJECTS : e.board === "IGCSE" ? IGCSE_SUBJECTS : BOTH_SUBJECTS),
  level: e.level ?? (e.board === "IGCSE" ? "Grades 9-10" : e.board === "IB" ? "PYP, MYP and DP (Grades 1-12)" : "IGCSE and IB, Grades 1-12"),
  focus: e.focus ?? `${e.keyword.replace(/ in india$/, "")} in India`,
  slug: e.slug,
  board: e.board,
  keyword: e.keyword,
  base: e.base,
  h1: e.h1,
  title: e.title,
  description: e.description,
  intent: e.intent,
  facts: e.facts,
  mustCover: e.mustCover,
  regions: e.regions,
  comparison: [...COMPARISONS[e.cmp]],
  secondary: [...CITIES.map((city) => `${e.base} in ${city}`), ...e.extras],
});

