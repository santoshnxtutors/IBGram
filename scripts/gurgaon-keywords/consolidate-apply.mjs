// Applies consolidation-plan.json: retires the 223 duplicate keyword pages into
// their 88 cluster survivors.
//
// Nothing is thrown away. Each survivor absorbs every retired sibling's
// secondary keywords and FAQs first, so the keyword coverage that justified
// those pages now lives on one URL that can actually rank, and the 301s hand it
// their accumulated signal.
//
//   node scripts/gurgaon-keywords/consolidate-apply.mjs           dry run
//   node scripts/gurgaon-keywords/consolidate-apply.mjs --write   apply
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const WRITE = process.argv.includes("--write");
const pagesPath = path.join(ROOT, "src/lib/gurgaon-keywords/pages.json");
const planPath = path.join(ROOT, "scripts/gurgaon-keywords/consolidation-plan.json");
const redirectsPath = path.join(ROOT, "src/lib/gurgaon-keywords/consolidation-redirects.ts");

const pages = JSON.parse(fs.readFileSync(pagesPath, "utf8"));
const plan = JSON.parse(fs.readFileSync(planPath, "utf8"));
const bySlug = new Map(pages.map((p) => [p.slug, p]));
const pathOf = (p) => new URL(p.canonicalUrl).pathname;

const norm = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
const redirects = [];
let kwAdded = 0, faqAdded = 0;
const retired = new Set();

for (const cluster of plan) {
  const keeper = pages.find((p) => pathOf(p) === cluster.keep);
  if (!keeper) { console.error(`missing keeper ${cluster.keep}`); continue; }

  const seenKw = new Set((keeper.secondaryKeywords ?? []).map(norm));
  seenKw.add(norm(keeper.primaryKeyword));
  const seenFaq = new Set((keeper.faqs ?? []).map((f) => norm(f.question)));

  for (const drop of cluster.drop) {
    const loser = bySlug.get(drop.slug);
    if (!loser) { console.error(`missing drop ${drop.slug}`); continue; }

    // The retired page's own head term is the most valuable thing it owned.
    for (const kw of [loser.primaryKeyword, ...(loser.secondaryKeywords ?? [])]) {
      if (!kw || seenKw.has(norm(kw))) continue;
      seenKw.add(norm(kw));
      keeper.secondaryKeywords = [...(keeper.secondaryKeywords ?? []), kw];
      kwAdded++;
    }
    for (const faq of loser.faqs ?? []) {
      if (seenFaq.has(norm(faq.question))) continue;
      seenFaq.add(norm(faq.question));
      keeper.faqs = [...(keeper.faqs ?? []), faq];
      faqAdded++;
    }
    redirects.push({ source: pathOf(loser), destination: cluster.keep });
    retired.add(loser.slug);
  }
}

const kept = pages.filter((p) => !retired.has(p.slug));
const header = `// Generated by scripts/gurgaon-keywords/consolidate-apply.mjs - do not hand-edit.
//
// ${redirects.length} Gurgaon keyword pages competed for the same handful of terms
// ("ib tutor", "ib tutors", "ib tuition", "best ib tutor", "ib coaching",
// "ib classes" all had their own URL), so Google picked none of them and ranked
// the whole cluster 40-90. Each one now points at its cluster's survivor, which
// carries their keywords and FAQs.
import type { Redirect } from "next/dist/lib/load-custom-routes";

export const gurgaonKeywordConsolidationRedirects: Redirect[] = [
`;
const body = redirects.map((r) => ` { source: "${r.source}", destination: "${r.destination}", permanent: true },`).join("\n");

console.log(`clusters            : ${plan.length}`);
console.log(`pages before        : ${pages.length}`);
console.log(`pages after         : ${kept.length}`);
console.log(`redirects written   : ${redirects.length}`);
console.log(`keywords absorbed   : ${kwAdded}`);
console.log(`FAQs absorbed       : ${faqAdded}`);
const maxKw = Math.max(...kept.map((p) => (p.secondaryKeywords ?? []).length));
const maxFaq = Math.max(...kept.map((p) => (p.faqs ?? []).length));
console.log(`largest survivor    : ${maxKw} secondary keywords, ${maxFaq} FAQs`);

// A survivor that swallowed 27 siblings must not end up a keyword dump: cap the
// list at a length a real page can use in copy, keeping the ones nearest the head term.
const CAP_KW = 40, CAP_FAQ = 20;
let capped = 0;
for (const p of kept) {
  if ((p.secondaryKeywords ?? []).length > CAP_KW) { p.secondaryKeywords = p.secondaryKeywords.slice(0, CAP_KW); capped++; }
  if ((p.faqs ?? []).length > CAP_FAQ) { p.faqs = p.faqs.slice(0, CAP_FAQ); }
}
console.log(`survivors capped    : ${capped} (keywords > ${CAP_KW})`);

if (!WRITE) { console.log("\ndry run - pass --write to apply"); process.exit(0); }
fs.writeFileSync(pagesPath, JSON.stringify(kept, null, 1).replace(/\r\n/g, "\n") + "\n", "utf8");
fs.writeFileSync(redirectsPath, header + body + "\n];\n", "utf8");
console.log(`\nwrote ${pagesPath}`);
console.log(`wrote ${redirectsPath}`);
